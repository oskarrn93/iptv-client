// PreToolUse hook for Edit/Write: catches what CI would reject, before the
// edit lands. Exit 2 blocks the edit and shows stderr to Claude.
import { readFileSync } from 'node:fs';

const { tool_input: input = {} } = JSON.parse(readFileSync(0, 'utf8'));
const path = (input.file_path ?? '').replaceAll('\\', '/');

function block(msg) {
  process.stderr.write(msg + '\n');
  process.exit(2);
}

if (/(^|\/)frontend\/wailsjs\//.test(path)) {
  block('frontend/wailsjs is generated. Change the exported App API in app.go, then run `go tool wails generate module`.');
}
if (path.endsWith('build/windows/installer/wails_tools.nsh')) {
  block('wails_tools.nsh is regenerated by Wails. Edit build/windows/installer/project.nsi instead.');
}

// Same pattern as the "Reject HTML sinks" step in .github/workflows/ci.yml.
const sinks = /innerHTML|outerHTML|insertAdjacentHTML|document\.write|\beval\(|new Function/;
if (/(^|\/)frontend\/src\//.test(path)) {
  const added = [input.content, input.new_string, ...(input.edits ?? []).map((e) => e.new_string)]
    .filter((s) => typeof s === 'string')
    .join('\n');
  const hit = added.match(sinks);
  if (hit) {
    block(`"${hit[0]}" is banned in frontend/src: playlist text is untrusted and CI rejects HTML sinks. Build DOM with h()/append from dom.ts.`);
  }
}
